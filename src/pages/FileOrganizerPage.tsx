import React, { useState } from 'react';
import {
  ArrowRight,
  BookOpen,
  CheckSquare,
  Download,
  FolderKanban,
  HardDrive,
  ShieldAlert,
  ShieldCheck,
  Square,
  Trash2,
} from 'lucide-react';
import {
  AppSettings,
  ConnectionCheckResult,
  FileOperationLog,
  FileOrganizeItem,
} from '../types';
import {
  applyFileOperationsViaBackend,
  BackendApiError,
  fetchFileSuggestionsFromBackend,
} from '../services/localAiService';
import { SAMPLE_DEMO_FILES } from '../data/demoData';
import { FileDropzone } from '../components/FileDropzone';
import { EmptyState } from '../components/EmptyState';
import { LoadingState } from '../components/LoadingState';
import { ErrorState } from '../components/ErrorState';
import { ConfirmDialog } from '../components/ConfirmDialog';
import { StatusBadge } from '../components/StatusBadge';

interface FileOrganizerPageProps {
  settings: AppSettings;
  connection: ConnectionCheckResult;
  files: FileOrganizeItem[];
  onSetFiles: React.Dispatch<React.SetStateAction<FileOrganizeItem[]>>;
  operationLogs: FileOperationLog[];
  onAddOperationLog: (log: FileOperationLog) => void;
  onLogActivity: (
    type: 'organize_files',
    status: 'success' | 'warning' | 'error' | 'info',
    description: string,
    sourceMode?: 'live-ollama' | 'demo-sample' | 'system'
  ) => void;
  onNotify: (
    title: string,
    description?: string,
    variant?: 'success' | 'warning' | 'error' | 'info'
  ) => void;
}

export const FileOrganizerPage: React.FC<FileOrganizerPageProps> = ({
  settings,
  connection,
  files,
  onSetFiles,
  operationLogs,
  onAddOperationLog,
  onLogActivity,
  onNotify,
}) => {
  const [isConfirmOpen, setIsConfirmOpen] = useState(false);
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const handleFilesSelected = async (selectedFiles: File[]) => {
    setError(null);
    setIsLoading(true);
    try {
      const enriched = await Promise.all(
        selectedFiles.map(async (f) => {
          let excerpt = '';
          if (/\.(txt|md|csv|json|log)$/i.test(f.name) && f.size < 200000) {
            try {
              const txt = await f.text();
              excerpt = txt.slice(0, 400);
            } catch {
              excerpt = '';
            }
          }
          return {
            name: f.name,
            type: f.type,
            size: f.size,
            lastModified: f.lastModified,
            contentExcerpt: excerpt,
          };
        })
      );

      const { items, model, sourceMode } =
        await fetchFileSuggestionsFromBackend(enriched, settings, true);

      onSetFiles((prev) => [...items, ...prev]);
      onLogActivity(
        'organize_files',
        'success',
        `Generated suggestions for ${items.length} file(s) via /api/organize/suggestions (${model}).`,
        sourceMode === 'live-ollama' ? 'live-ollama' : 'system'
      );
      onNotify(
        `Suggested renames for ${items.length} file(s)`,
        sourceMode === 'live-ollama'
          ? `Generated by ${model} via /api/organize/suggestions.`
          : 'Generated via backend deterministic rule engine (Ollama offline).',
        'success'
      );
    } catch (err) {
      const msg =
        err instanceof BackendApiError
          ? err.message
          : 'Failed to generate file suggestions.';
      setError(msg);
    } finally {
      setIsLoading(false);
    }
  };

  const handleLoadDemoFiles = () => {
    setError(null);
    onSetFiles(SAMPLE_DEMO_FILES);
    onLogActivity(
      'organize_files',
      'info',
      'Loaded 4 clearly labeled Demo Data files into File Organizer.',
      'demo-sample'
    );
    onNotify(
      'Demo files loaded',
      'Loaded 4 sample messy filenames (labeled as Demo Data).',
      'info'
    );
  };

  const handleToggleApprove = (id: string) => {
    onSetFiles((prev) =>
      prev.map((f) => (f.id === id ? { ...f, approved: !f.approved } : f))
    );
  };

  const handleSelectAll = () => {
    onSetFiles((prev) => prev.map((f) => ({ ...f, approved: true })));
  };

  const handleDeselectAll = () => {
    onSetFiles((prev) => prev.map((f) => ({ ...f, approved: false })));
  };

  const handleUpdateSuggestion = (
    id: string,
    field: 'suggestedFilename' | 'suggestedFolder' | 'sourceRelativePath',
    value: string
  ) => {
    onSetFiles((prev) =>
      prev.map((f) => (f.id === id ? { ...f, [field]: value } : f))
    );
  };

  const approvedFiles = files.filter((f) => f.approved);

  const handleDryRunPreview = async () => {
    if (approvedFiles.length === 0) return;
    setError(null);
    setIsLoading(true);
    try {
      const res = await applyFileOperationsViaBackend(
        approvedFiles,
        true,
        false,
        settings
      );
      onSetFiles((prev) =>
        prev.map((f) =>
          f.approved ? { ...f, status: 'preview-validated' } : f
        )
      );
      onAddOperationLog({
        id: `op-${Date.now()}`,
        timestamp: new Date().toISOString(),
        fileCount: res.results.length,
        status: 'preview-validated',
        message: `Pre-flight path & symlink check passed for ${res.results.length} file(s) inside ${res.allowed_root}.`,
        details: res.results.map(
          (r) =>
            `[VALIDATED PREVIEW] ${r.source_relative_path} → ${r.destination_relative_path}`
        ),
      });
      onNotify(
        'Pre-flight validation passed',
        `Verified ${res.results.length} path(s) inside ${res.allowed_root}.`,
        'success'
      );
    } catch (err) {
      const msg =
        err instanceof BackendApiError
          ? err.message
          : 'Pre-flight validation failed.';
      setError(msg);
    } finally {
      setIsLoading(false);
    }
  };

  const handleApplyApproved = async () => {
    setIsConfirmOpen(false);
    if (approvedFiles.length === 0) return;

    setError(null);
    setIsLoading(true);
    try {
      const res = await applyFileOperationsViaBackend(
        approvedFiles,
        false,
        true,
        settings
      );

      onSetFiles((prev) =>
        prev.map((f) => (f.approved ? { ...f, status: 'applied' } : f))
      );

      const newLog: FileOperationLog = {
        id: `op-${Date.now()}`,
        timestamp: new Date().toISOString(),
        fileCount: res.results.length,
        status: 'applied',
        message: `Applied ${res.results.length} approved file operation(s) in ${res.allowed_root}.`,
        details: res.results.map(
          (r) =>
            `[${r.status.toUpperCase()}] ${r.source_relative_path} → ${
              r.destination_relative_path
            }`
        ),
      };

      onAddOperationLog(newLog);
      onLogActivity(
        'organize_files',
        'success',
        `Applied ${res.results.length} approved file operation(s) via /api/organize/apply.`,
        'system'
      );
      onNotify(
        'Approved changes applied',
        `Moved/renamed ${res.results.length} file(s) inside ${res.allowed_root}.`,
        'success'
      );
    } catch (err) {
      const msg =
        err instanceof BackendApiError
          ? err.message
          : 'Failed to apply file operations.';
      setError(msg);
      onLogActivity(
        'organize_files',
        'error',
        `File apply rejected: ${msg}`,
        'system'
      );
    } finally {
      setIsLoading(false);
    }
  };

  const handleDownloadManifest = () => {
    if (approvedFiles.length === 0) return;
    const manifest = {
      generatedBy: 'SlothAI File Organizer',
      generatedAt: new Date().toISOString(),
      targetEndpoint: 'POST /api/organize/apply',
      operations: approvedFiles.map((f) => ({
        source_relative_path: f.sourceRelativePath || f.originalName,
        destination_folder: f.suggestedFolder,
        new_filename: f.suggestedFilename,
        approved: f.approved,
        isDemoData: f.isDemoData,
      })),
    };

    const blob = new Blob([JSON.stringify(manifest, null, 2)], {
      type: 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `slothai-file-plan-${Date.now()}.json`;
    a.click();
    URL.revokeObjectURL(url);
    onNotify(
      'Downloaded JSON Manifest',
      'Exported approved file organization plan.',
      'success'
    );
  };

  const formatBytes = (bytes: number | null) => {
    if (bytes === null || Number.isNaN(bytes)) return '—';
    if (bytes < 1024) return `${bytes} B`;
    const kb = bytes / 1024;
    if (kb < 1024) return `${kb.toFixed(1)} KB`;
    return `${(kb / 1024).toFixed(2)} MB`;
  };

  return (
    <div className="space-y-6 pb-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <span className="text-[10px] font-mono uppercase tracking-[0.18em] text-[#FF9A35]">
            [ 03 · SAFE STAGING ]
          </span>
          <h1 className="mt-1 text-2xl font-display font-bold tracking-tight text-[#F5F5F5]">
            Intelligent File Organizer
          </h1>
          <p className="mt-1 text-xs text-[#A1A1AA]">
            Generates safe suggestions via <code className="font-mono text-[#FF9A35]">POST /api/organize/suggestions</code> and applies approved moves inside your configured root via <code className="font-mono text-[#FF9A35]">POST /api/organize/apply</code>.
          </p>
        </div>

        <div className="flex items-center gap-2 shrink-0">
          <button
            type="button"
            onClick={handleLoadDemoFiles}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium rounded-full border border-white/12 bg-[#121215] text-[#F5F5F5] hover:border-[#FF9A35]/50 hover:bg-white/[0.06] transition-colors whitespace-nowrap shrink-0 cursor-pointer"
          >
            <BookOpen className="w-3.5 h-3.5 text-[#FF9A35]" />
            <span>Load Sample Files (Demo Data)</span>
          </button>
          {files.length > 0 && (
            <button
              type="button"
              onClick={() => onSetFiles([])}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium rounded-full border border-red-500/30 text-[#F87171] hover:bg-red-950/30 transition-colors whitespace-nowrap shrink-0 cursor-pointer"
            >
              <Trash2 className="w-3.5 h-3.5" />
              <span>Clear Staging Table</span>
            </button>
          )}
        </div>
      </div>

      {/* Directory Security Status Banner */}
      <div className="p-4 rounded-2xl border border-white/[0.08] bg-[#0B0B0C] flex items-start gap-3.5">
        {connection.organizeRootConfigured ? (
          <ShieldCheck className="w-4 h-4 text-[#4ADE80] mt-0.5 shrink-0" />
        ) : (
          <ShieldAlert className="w-4 h-4 text-[#FFA726] mt-0.5 shrink-0" />
        )}
        <div className="text-xs leading-relaxed text-[#A1A1AA]">
          {connection.organizeRootConfigured ? (
            <>
              <span className="font-semibold text-[#F5F5F5]">
                Allowed Organize Root Directory Active:{' '}
              </span>
              Filesystem operations are strictly confined to{' '}
              <code className="font-mono px-1.5 py-0.5 rounded bg-[#141418] border border-white/10 text-[#FF9A35]">
                {connection.allowedOrganizeRoot}
              </code>
              . Path traversal (<code className="font-mono text-[#F5F5F5]">..</code>), symlinks, and file overwrites are automatically blocked.
            </>
          ) : (
            <>
              <span className="font-semibold text-[#F5F5F5]">
                Suggestions-Only Mode (Filesystem Modifications Disabled by Default):{' '}
              </span>
              Browser inputs cannot arbitrarily access your disk, and{' '}
              <code className="font-mono text-[#FF9A35]">SLOTHAI_ALLOWED_ORGANIZE_ROOT</code> is not currently set on the backend. You can generate suggestions and export JSON plans now; to enable live file moves via{' '}
              <code className="font-mono text-[#F5F5F5]">POST /api/organize/apply</code>, set{' '}
              <code className="font-mono text-[#FF9A35]">SLOTHAI_ALLOWED_ORGANIZE_ROOT</code> in <code className="font-mono text-[#F5F5F5]">backend/.env</code>.
            </>
          )}
        </div>
      </div>

      {error && (
        <ErrorState
          title="File Organizer Security / Backend Notice"
          message={error}
          onDismiss={() => setError(null)}
        />
      )}

      {/* Dropzone */}
      <FileDropzone
        accept="*"
        multiple
        label="Select or drag & drop files to request organization suggestions"
        helperText="Sends file metadata (and short text excerpts for .txt/.md) to POST /api/organize/suggestions without modifying files."
        onFilesSelected={handleFilesSelected}
      />

      {isLoading && (
        <LoadingState
          label="Processing file organization request via backend..."
          rows={3}
        />
      )}

      {/* Staging Table */}
      {files.length > 0 ? (
        <div className="space-y-4">
          {/* Batch Controls Bar */}
          <div className="flex flex-wrap items-center justify-between gap-3 p-4 rounded-2xl border border-white/[0.08] bg-[#0B0B0C]">
            <div className="flex flex-wrap items-center gap-3">
              <button
                type="button"
                onClick={handleSelectAll}
                className="inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-full border border-white/12 bg-[#121215] text-[#F5F5F5] hover:bg-white/[0.06] transition-colors whitespace-nowrap shrink-0 cursor-pointer"
              >
                <CheckSquare className="w-3.5 h-3.5 text-[#FF9A35]" />
                <span>Select All</span>
              </button>
              <button
                type="button"
                onClick={handleDeselectAll}
                className="inline-flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-full border border-white/12 bg-[#121215] text-[#A1A1AA] hover:text-[#F5F5F5] transition-colors whitespace-nowrap shrink-0 cursor-pointer"
              >
                <Square className="w-3.5 h-3.5" />
                <span>Deselect All</span>
              </button>
              <span className="text-xs font-mono tabular-nums text-[#71717A]">
                {approvedFiles.length} of {files.length} approved
              </span>
            </div>

            <div className="flex flex-wrap items-center gap-2.5">
              <button
                type="button"
                onClick={handleDownloadManifest}
                disabled={approvedFiles.length === 0}
                className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium rounded-full border border-white/12 bg-[#121215] text-[#F5F5F5] hover:bg-white/[0.06] transition-colors whitespace-nowrap shrink-0 cursor-pointer disabled:opacity-40"
              >
                <Download className="w-3.5 h-3.5 text-[#FF9A35]" />
                <span>Export JSON Plan ({approvedFiles.length})</span>
              </button>
              <button
                type="button"
                onClick={handleDryRunPreview}
                disabled={approvedFiles.length === 0 || isLoading}
                className="inline-flex items-center gap-1.5 px-3.5 py-2 text-xs font-medium rounded-full border border-[#FF6B1A]/35 bg-[#FF6B1A]/15 text-[#FF9A35] hover:bg-[#FF6B1A]/25 transition-colors whitespace-nowrap shrink-0 cursor-pointer disabled:opacity-40"
              >
                <span>Validate Preview (Dry Run)</span>
              </button>
              <button
                type="button"
                onClick={() => setIsConfirmOpen(true)}
                disabled={approvedFiles.length === 0 || isLoading}
                className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold rounded-full bg-gradient-to-r from-[#FF6B1A] to-[#FF9A35] text-black hover:brightness-110 transition-all whitespace-nowrap shrink-0 cursor-pointer disabled:opacity-40"
              >
                <FolderKanban className="w-3.5 h-3.5" />
                <span>Apply Approved Changes ({approvedFiles.length})</span>
              </button>
            </div>
          </div>

          {/* Before & After Comparison Table */}
          <div className="rounded-2xl border border-white/[0.08] bg-[#0B0B0C] overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-white/[0.08] text-[11px] font-mono uppercase tracking-wider text-[#71717A] bg-[#060606]">
                  <th className="py-3.5 px-4 w-10">Approve</th>
                  <th className="py-3.5 px-4">Original Relative Path (Before)</th>
                  <th className="py-3.5 px-4">Category &amp; Size</th>
                  <th className="py-3.5 px-4">Suggested Destination &amp; Rename (After)</th>
                  <th className="py-3.5 px-4">State</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-white/[0.08] text-xs">
                {files.map((item) => (
                  <tr
                    key={item.id}
                    className={`transition-colors ${
                      item.approved
                        ? 'bg-[#0B0B0C]'
                        : 'bg-[#060606]/70 opacity-65'
                    }`}
                  >
                    <td className="py-3.5 px-4 align-top">
                      <input
                        type="checkbox"
                        checked={item.approved}
                        onChange={() => handleToggleApprove(item.id)}
                        aria-label={`Approve rename for ${item.originalName}`}
                        className="w-4 h-4 rounded border-white/20 bg-[#060606] accent-[#FF6B1A] cursor-pointer"
                      />
                    </td>

                    <td className="py-3.5 px-4 align-top max-w-xs">
                      <div className="font-mono font-medium text-[#F5F5F5] break-all">
                        {item.originalName}
                      </div>
                      <div className="mt-1 flex items-center gap-2 text-[11px] text-[#71717A]">
                        <span>.{item.extension}</span>
                        <span aria-hidden="true">·</span>
                        <span>{item.isDemoData ? 'Demo Data' : 'Selected File'}</span>
                      </div>
                      <p className="mt-1 text-[11px] text-[#A1A1AA]">
                        {item.reasoning}
                      </p>
                    </td>

                    <td className="py-3.5 px-4 align-top whitespace-nowrap">
                      <div className="font-medium text-[#F5F5F5]">
                        {item.suggestedCategory}
                      </div>
                      <div className="mt-1 font-mono tabular-nums text-[11px] text-[#71717A]">
                        {formatBytes(item.sizeBytes)}
                      </div>
                    </td>

                    <td className="py-3.5 px-4 align-top min-w-[280px]">
                      <div className="space-y-2">
                        <div className="flex items-center gap-1.5">
                          <span className="text-[11px] text-[#71717A] w-14 shrink-0">
                            Folder:
                          </span>
                          <input
                            type="text"
                            value={item.suggestedFolder}
                            onChange={(e) =>
                              handleUpdateSuggestion(
                                item.id,
                                'suggestedFolder',
                                e.target.value
                              )
                            }
                            aria-label={`Suggested destination folder for ${item.originalName}`}
                            className="w-full px-2.5 py-1 text-xs font-mono rounded-lg border border-white/12 bg-[#060606] text-[#F5F5F5]"
                          />
                        </div>
                        <div className="flex items-center gap-1.5">
                          <span className="text-[11px] text-[#71717A] w-14 shrink-0">
                            Rename:
                          </span>
                          <input
                            type="text"
                            value={item.suggestedFilename}
                            onChange={(e) =>
                              handleUpdateSuggestion(
                                item.id,
                                'suggestedFilename',
                                e.target.value
                              )
                            }
                            aria-label={`Suggested filename for ${item.originalName}`}
                            className="w-full px-2.5 py-1 text-xs font-mono rounded-lg border border-white/12 bg-[#060606] text-[#FF9A35] font-medium"
                          />
                        </div>
                        <div className="flex items-center gap-1.5 text-[11px] text-[#71717A]">
                          <span className="font-mono truncate max-w-[130px]">
                            {item.originalName}
                          </span>
                          <ArrowRight className="w-3 h-3 shrink-0 text-[#FF9A35]" />
                          <span className="font-mono text-[#F5F5F5] truncate">
                            {item.suggestedFolder}/{item.suggestedFilename}
                          </span>
                        </div>
                      </div>
                    </td>

                    <td className="py-3.5 px-4 align-top whitespace-nowrap">
                      {item.status === 'applied' ? (
                        <StatusBadge status="success" label="Applied on Disk" />
                      ) : item.status === 'preview-validated' ? (
                        <StatusBadge status="info" label="Preview Validated" />
                      ) : item.isDemoData ? (
                        <StatusBadge status="warning" label="Demo Preview" />
                      ) : (
                        <StatusBadge status="pending" label="Awaiting Approval" />
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      ) : (
        <EmptyState
          title="No files staged for organization"
          description="Select or drag files above to request suggestions from POST /api/organize/suggestions, or load the sample messy folder dataset."
          actionLabel="Load Sample Files (Demo Data)"
          onAction={handleLoadDemoFiles}
        />
      )}

      {/* Operation Log */}
      <section aria-labelledby="file-op-log-heading" className="pt-2">
        <div className="flex items-center gap-2 mb-3">
          <HardDrive className="w-4 h-4 text-[#FF9A35]" />
          <h2
            id="file-op-log-heading"
            className="text-sm font-display font-semibold uppercase tracking-[0.14em] text-[#F5F5F5]"
          >
            File Organization Operation Log
          </h2>
        </div>

        {operationLogs.length === 0 ? (
          <div className="p-4 rounded-2xl border border-white/[0.08] bg-[#0B0B0C] text-xs text-[#71717A]">
            No batch organization operations have been executed in this session yet.
          </div>
        ) : (
          <div className="space-y-3">
            {operationLogs.map((log) => (
              <div
                key={log.id}
                className="p-4 rounded-2xl border border-white/[0.08] bg-[#0B0B0C]"
              >
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <StatusBadge status="success" label={log.message} />
                  <span className="text-[11px] font-mono tabular-nums text-[#71717A]">
                    {new Date(log.timestamp).toLocaleTimeString()}
                  </span>
                </div>
                <ul className="mt-2.5 space-y-1 pl-4 border-l border-white/15 font-mono text-[11px] text-[#A1A1AA]">
                  {log.details.map((line, idx) => (
                    <li key={idx}>{line}</li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
        )}
      </section>

      <ConfirmDialog
        isOpen={isConfirmOpen}
        title={`Apply ${approvedFiles.length} Approved File Operation(s)?`}
        description={
          connection.organizeRootConfigured
            ? `This will send ${approvedFiles.length} explicitly approved file move/rename operation(s) to POST /api/organize/apply within "${connection.allowedOrganizeRoot}". Existing files will never be overwritten.`
            : 'SLOTHAI_ALLOWED_ORGANIZE_ROOT is not currently configured on the backend, so POST /api/organize/apply will safely reject filesystem changes until you configure an allowed root directory in backend/.env.'
        }
        confirmLabel="Confirm & Send to /api/organize/apply"
        onConfirm={handleApplyApproved}
        onCancel={() => setIsConfirmOpen(false)}
      />
    </div>
  );
};
